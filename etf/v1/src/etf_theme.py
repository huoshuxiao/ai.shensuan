# -*- coding: utf-8 -*-
"""ETF 主题分类：从 ETF 名字（+跟踪指数名）抠出「粗类」和「方向」两层。

**定位：只给看板当观察项，不进任何判据、不进选股、不进权重。**
这条线真正的决策面是 `strategy.select_weights` + `PORTFOLIO`，本模块一个字都不参与。
谁要把「每方向最多 N 席」真的接进决策，先重跑 `etf/v1/temp/conc_tiers*_0927.py`
那两张档位表（实测读数见那两个脚本的 docstring），那是判据变更、要单独拍板。

为什么要有「方向」这一层（粗类不够用）
------------------------------------
盘上唯一的现成分类是 `etf_universe_cache.csv` 的 `index_group`（跟踪指数名），
而候选池本来就是**每个指数组只留一只代表**建出来的 ⇒ 100 只对应 100 个不同的组，
每组恰好 1 只。拿它做"同一类最多 N 席"是空判据（N≥1 永不咬）。
往下合并两层才有效：
    index_group（100 个）→ category（17 个粗类）→ direction（10 个方向）
用户在意的那句"10 只里 7 只科技/科创/军工"对应的是 **direction**（成长系）这一层，
在 17 类口径下同一篮会被读成"分布在 9 个类里、挺分散"。两层都留着，
因为档位实测显示：**维度粗细直接决定账单**（粗类≤2 席 总收益 −46.7%，
方向≤2 席 −38.8%，现状 −36.2%）。

口径（改一行都要重跑档位表并同步看板措辞）
----------------------------------------
1. 一只 ETF 只归一个粗类：`RULES` **从上到下第一个命中即止**，越具体越靠前
   （`半导体电子` 在 `科技综合` 前面，否则"科创芯片设计"会掉进科技综合）。
2. 匹配文本是 `"{name}|{index_group}"`，名字里没写、指数名里有的关键词也能命中。
3. 维度取**主题/方向**而非地域：纳指科技与科创芯片同涨同跌 ⇒ 同归成长系；
   黄金/豆粕与股票不是同一资产 ⇒ 单列商品。所以 恒生科技→科技综合（不归港股）、
   纳指生物科技→医药（不归海外宽基）、黄金股→商品（不归周期）——这三条
   是**我拍的**，人眼没确认前它们只影响观察项、不影响任何判据。
4. 未命中给 `未分类`：候选池实测 100/100 全命中；全市场镜像（871 只）会有
   未分类的，那是要新增长尾品种时必然的维护点。
"""
import re

# (粗类, 正则) —— 从上到下第一个命中即止：先具体主题、后地域/宽基
RULES = [
    ("黄金与商品", r"黄金|金ETF|豆粕|油气|粮食"),
    ("债券货币", r"债|货币|理财"),
    ("半导体电子", r"半导体|芯片|消费电子|集成电路"),
    ("人工智能软件通信", r"人工智能|AI|软件|通信"),
    ("军工航天", r"军工|卫星"),
    ("新能源与高端制造", r"电池|储能|新能源|电网|材料"),
    ("医药", r"创新药|医药|医疗|生物|疫苗"),
    ("金融", r"证券|券商|保险|非银|金融科技|银行"),
    ("周期资源", r"有色|煤炭|化工|石油|能源|电力|钢|建材|矿业"),
    ("消费传媒", r"酒|旅游|游戏|传媒|消费|食品|农业|养殖"),
    ("平台互联网", r"互联网|中概"),
    ("红利低波", r"红利|低波"),
    ("价值", r"价值"),
    ("科创创业成长风格", r"科创|创业板|成长"),
    ("科技综合", r"科技"),
    ("港股", r"港股|恒生|H股|中国企业"),
    ("海外宽基", r"纳指|纳斯达克|标普|道琼斯|日经|美国|法国|德国|亚太"),
    ("A股宽基", r"50|300|500|1000|2000|A5|100|上证|沪深|中证"),
]

# 粗类 → 方向（更粗的一层，10 个方向 + 未分类）
DIRECTION = {
    "半导体电子": "成长系", "人工智能软件通信": "成长系", "军工航天": "成长系",
    "新能源与高端制造": "成长系", "科技综合": "成长系",
    "科创创业成长风格": "成长系", "平台互联网": "成长系",
    "医药": "医药", "金融": "金融", "周期资源": "周期",
    "消费传媒": "消费", "红利低波": "红利价值", "价值": "红利价值",
    "黄金与商品": "商品", "债券货币": "债券货币",
    "港股": "港股", "海外宽基": "海外宽基", "A股宽基": "A股宽基",
}

UNCLASSIFIED = "未分类"


def category_of(name, index_group=""):
    """一只 ETF → 粗类（17 个之一），未命中返回 `未分类`。"""
    text = f"{name or ''}|{index_group or ''}"
    for cat, pat in RULES:
        if re.search(pat, text):
            return cat
    return UNCLASSIFIED


def direction_of(name, index_group=""):
    """一只 ETF → 方向（10 个之一）。方向是粗类的纯映射，不再碰正则。"""
    return DIRECTION.get(category_of(name, index_group), UNCLASSIFIED)


def weight_by_direction(rows, weight_col="weight",
                        name_col="name", group_col="index_group"):
    """把一篮持仓按方向汇总成权重（占该篮合计权重的比例）。

    rows 需带 `name`（或能从 index_group 抠出主题）与 weight 两列。
    返回 {方向: 权重合计}，未命中给 `未分类`——**这一格是要上看板的，
    所以未分类必须显式可见，不能悄悄并进别的方向**。"""
    out = {}
    for r in rows.itertuples(index=False):
        d = direction_of(getattr(r, name_col, ""),
                         getattr(r, group_col, ""))
        out[d] = out.get(d, 0.0) + float(getattr(r, weight_col))
    return out
